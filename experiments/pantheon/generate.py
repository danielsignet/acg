def state(parent, **attrs):
    return ET.SubElement(parent,"state",{k:str(v).lower() if isinstance(v,bool) else str(v) for k,v in attrs.items()})


def transform(parent,name,pos=(0,0,0),scale=(1,1,1),rot=(0,0,0),ref=None,mat=None,exact=False,pick=False,**attrs):
    TRANSFORMS[name] = TRANSFORMS.get(name, 0) + 1
    if not exact: name = f"{name} {TRANSFORMS[name]:03}"
    e=ET.SubElement(parent,"transform",name=name,translate=vec(pos),scale=vec(scale),rotate=vec(rot),**attrs)
    if mat: state(e,**mat)
    if ref: ET.SubElement(e,"instance",ref=ref,name=name,selectable=str(pick).lower())
    return e


def group(parent,name,**attrs):
    return ET.SubElement(parent,"group",name=name,**attrs)


def asset(parent,name,mesh,mats):
    e=ET.SubElement(parent,"model",id=name,file=PREFIX+"meshes/"+mesh+".obj")
    for key,values in mats.items():
        ET.SubElement(e,"material",name=key,**{k:str(v).lower() if isinstance(v,bool) else str(v) for k,v in values.items()})
    return e


