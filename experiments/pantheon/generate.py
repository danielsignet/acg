def vec(v):
    return " ".join(f"{x:.7g}" for x in v)


def sub(a, b):
    return tuple(x-y for x, y in zip(a, b))


def cross(a, b):
    return (a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0])


def dot(a, b):
    return sum(x*y for x, y in zip(a, b))


class Mesh:
    def __init__(self):
        self.lines = ["# ACG Pantheon experiment: generated by generate.py", "mtllib prototype.mtl"]
        self.vertices = 0
        self.triangles = 0

    def poly(self, points, normal, uv=None, material="stone", vertex_normals=None):
        face_normal = cross(sub(points[1], points[0]), sub(points[2], points[0]))
        length = math.sqrt(dot(face_normal, face_normal))
        if length < 1e-10:
            return
        if uv is None:
            # Project onto the actual face plane. X/Y collapsed horizontal
            # cornice caps to a line, leaving them without usable tangents.
            dominant = max(range(3), key=lambda axis: abs(face_normal[axis]))
            axes = (2, 1) if dominant == 0 else (0, 2) if dominant == 1 else (0, 1)
            uv = [(p[axes[0]]/3, p[axes[1]]/3) for p in points]
        if dot(face_normal, normal) < 0:
            points, uv = list(reversed(points)), list(reversed(uv))
            if vertex_normals: vertex_normals = list(reversed(vertex_normals))
            face_normal = tuple(-x for x in face_normal)
        face_normal = tuple(x/length for x in face_normal)
        self.lines.append("usemtl " + material)
        start = self.vertices + 1
        for p, t, n in zip(points, uv, vertex_normals or [face_normal]*len(points)):
            n_length=math.sqrt(dot(n,n))
            self.lines.extend(["v " + vec(p), "vt " + vec(t), "vn " + vec(tuple(x/n_length for x in n))])
            self.vertices += 1
        for i in range(1, len(points)-1):
            triangle_normal=cross(sub(points[i],points[0]),sub(points[i+1],points[0]))
            if dot(triangle_normal,triangle_normal)<1e-20:
                continue
            ids = (start, start+i, start+i+1)
            self.lines.append("f " + " ".join(f"{j}/{j}/{j}" for j in ids))
            self.triangles += 1

    def box(self, center, size, material="stone"):
        x, y, z = center
        a, b, c = (s/2 for s in size)
        for points, n in [
            ([(x-a,y-b,z+c),(x+a,y-b,z+c),(x+a,y+b,z+c),(x-a,y+b,z+c)], (0,0,1)),
            ([(x+a,y-b,z-c),(x-a,y-b,z-c),(x-a,y+b,z-c),(x+a,y+b,z-c)], (0,0,-1)),
            ([(x-a,y-b,z-c),(x-a,y-b,z+c),(x-a,y+b,z+c),(x-a,y+b,z-c)], (-1,0,0)),
            ([(x+a,y-b,z+c),(x+a,y-b,z-c),(x+a,y+b,z-c),(x+a,y+b,z+c)], (1,0,0)),
            ([(x-a,y+b,z+c),(x+a,y+b,z+c),(x+a,y+b,z-c),(x-a,y+b,z-c)], (0,1,0)),
            ([(x-a,y-b,z-c),(x+a,y-b,z-c),(x+a,y-b,z+c),(x-a,y-b,z+c)], (0,-1,0))]:
            axes = [i for i, v in enumerate(n) if not v]
            self.poly(points, n, [(p[axes[0]]/3,p[axes[1]]/3) for p in points], material)

    def save(self, name):
        # OBJ import splits contiguous material runs. Group faces here so a tiled
        # floor is three material meshes, not hundreds of tiny imported meshes.
        geometry, faces, current = [], {}, "stone"
        for line in self.lines:
            if line.startswith("usemtl "):
                current = line[7:]
            elif line.startswith("f "):
                faces.setdefault(current, []).append(line)
            else:
                geometry.append(line)
        for material, lines in faces.items():
            geometry.extend(["usemtl " + material, *lines])
        (HERE / "meshes" / (name+".obj")).write_text("\n".join(geometry)+"\n", encoding="ascii")
        COUNTS[name] = {"vertices_before_import": self.vertices, "triangles": self.triangles}


def annulus(mesh, inner, outer, y, material="marble", steps=112):
    for i in range(steps):
        a, b = i*math.tau/steps, (i+1)*math.tau/steps
        if inner == 0:
            pts = [(0,y,0),(outer*math.sin(a),y,-outer*math.cos(a)),(outer*math.sin(b),y,-outer*math.cos(b))]
        else:
            pts = [(r*math.sin(t),y,-r*math.cos(t)) for r,t in [(inner,a),(outer,a),(outer,b),(inner,b)]]
        mesh.poly(pts,(0,1,0),[(p[0]/3,p[2]/3) for p in pts],material)


def make_arch():
    mesh = Mesh()
    # Real arched opening: 6 m wide, 4.4 m spring, 7.4 m crown.
    for i in range(24):
        t0, t1 = i*math.pi/24, (i+1)*math.pi/24
        x0, x1 = 3*math.cos(t0), 3*math.cos(t1)
        y0, y1 = 4.4+3*math.sin(t0), 4.4+3*math.sin(t1)
        for z,n in [(-DOOR+.02,(0,0,1)),(-DOOR-1.1,(0,0,-1))]:
            mesh.poly([(x0,y0,z),(x1,y1,z),(x1,R,z),(x0,R,z)],n)
        mesh.poly([(x0,y0,-DOOR+.02),(x0,y0,-DOOR-1.1),(x1,y1,-DOOR-1.1),(x1,y1,-DOOR+.02)],
                  (-math.cos((t0+t1)/2),-math.sin((t0+t1)/2),0))
    for side in (-1,1):
        mesh.box((side*(HALF+3)/2,R/2,-DOOR-.54),(HALF-3,R,1.12))
    mesh.save("door-bay")
    trim=Mesh()
    for i in range(32):
        a,b=i*math.pi/32,(i+1)*math.pi/32
        pts=[(r*math.cos(t),4.4+r*math.sin(t),-DOOR+.08) for r,t in [(3,a),(3.23,a),(3.23,b),(3,b)]]
        trim.poly(pts,(0,0,1),material="bronze")
    for side in (-1,1):
        trim.box((side*3.115,2.2,-DOOR+.08),(.23,4.4,.12),"bronze")
    trim.save("arch-trim")


def make_column(segments, name):
    mesh=Mesh()
    profile=[(0,.95),(.18,.95),(.22,.83),(.4,.83),(.5,.66),(.7,.62),
             (10.8,.52),(11,.66),(11.15,.75),(11.35,.75),(11.4,.96),(11.8,.96)]
    for (y0,r0),(y1,r1) in zip(profile,profile[1:]):
        for i in range(segments):
            a,b=i*math.tau/segments,(i+1)*math.tau/segments
            pts=[(r*math.sin(t),y,r*math.cos(t)) for r,y,t in [(r0,y0,a),(r0,y0,b),(r1,y1,b),(r1,y1,a)]]
            n=(math.sin((a+b)/2),(r0-r1)/(y1-y0),math.cos((a+b)/2))
            normals=[(math.sin(t),(r0-r1)/(y1-y0),math.cos(t)) for t in (a,b,b,a)]
            mesh.poly(pts,n,[(t*r/3,y/3) for r,y,t in [(r0,y0,a),(r0,y0,b),(r1,y1,b),(r1,y1,a)]],"marble",normals)
    annulus(mesh,0,.96,11.8,"marble",segments)
    mesh.save(name)


def make_dome(row, low=False):
    mesh=Mesh()
    phi_min=math.asin(OCULUS/R)
    ph0=phi_min+(math.pi/2-phi_min)*row/5
    ph1=phi_min+(math.pi/2-phi_min)*(row+1)/5
    grid=[0,.1,.2,.4,.6,.8,.9,1] if not low else [0,.2,.8,1]
    def point(u,v):
        phi=ph0+(ph1-ph0)*v
        a=(u-.5)*math.tau/28
        recess=.28 if .19<u<.81 and .19<v<.81 else .07 if .09<u<.91 and .09<v<.91 else 0
        radius=R+recess
        return (radius*math.sin(phi)*math.sin(a),R+radius*math.cos(phi),-radius*math.sin(phi)*math.cos(a))
    for i in range(len(grid)-1):
        for j in range(len(grid)-1):
            uv=[(grid[i],grid[j]),(grid[i+1],grid[j]),(grid[i+1],grid[j+1]),(grid[i],grid[j+1])]
            pts=[point(u,v) for u,v in uv]
            c=point((grid[i]+grid[i+1])/2,(grid[j]+grid[j+1])/2)
            # Equal texel density in metres for every coffer row and both LODs.
            middle_phi=(ph0+ph1)/2
            width=R*math.sin(middle_phi)*math.tau/28
            mesh.poly(pts,(-c[0],R-c[1],-c[2]),[(u*width/3,R*(ph0+v*(ph1-ph0))/3) for u,v in uv])
    mesh.save(f"coffer-{row}"+("-low" if low else ""))


